
import os
from pathlib import Path

import psycopg
from dotenv import load_dotenv


# Load DATABASE_URL from the project's root .env file.
PROJECT_ROOT = Path(__file__).resolve().parent.parent
load_dotenv(PROJECT_ROOT / ".env")

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is missing from the .env file.")


SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS resumes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    source_type TEXT DEFAULT 'created',
    uploaded_filename TEXT,
    extracted_text TEXT,
    personal_info TEXT,
    summary TEXT,
    education TEXT,
    skills TEXT,
    projects TEXT,
    experience TEXT,
    certifications TEXT,
    custom_sections TEXT,
    completion INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resume_number INTEGER
);

CREATE TABLE IF NOT EXISTS ats_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    resume_id BIGINT NOT NULL REFERENCES resumes(id),
    resume_title TEXT NOT NULL,
    job_title TEXT,
    job_description TEXT NOT NULL,
    score DOUBLE PRECISION,
    analysis_json TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    analysis_number INTEGER
);

CREATE INDEX IF NOT EXISTS idx_ats_analyses_user_created
ON ats_analyses(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_ats_analyses_resume_created
ON ats_analyses(resume_id, created_at DESC);
"""


def main():
    with psycopg.connect(DATABASE_URL, connect_timeout=10) as conn:
        with conn.cursor() as cursor:
            cursor.execute(SCHEMA)

            cursor.execute("""
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = 'public'
                  AND table_name IN (
                      'users', 'resumes', 'ats_analyses'
                  )
                ORDER BY table_name
            """)

            tables = [row[0] for row in cursor.fetchall()]

    expected = {"users", "resumes", "ats_analyses"}

    if set(tables) != expected:
        raise RuntimeError(f"Unexpected table list: {tables}")

    print("PostgreSQL schema created successfully.")
    print("Tables:", ", ".join(tables))
    print("No existing records were migrated or deleted.")


if __name__ == "__main__":
    main()
