
import os
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv


PROJECT_ROOT = Path(__file__).resolve().parent.parent
load_dotenv(PROJECT_ROOT / ".env")

DATABASE_URL = os.getenv("DATABASE_URL")


def get_db_connection():
    """Create a PostgreSQL connection to the Novus Neon database."""
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Set it in your local .env file "
            "or in the Render environment variables."
        )

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=10,
    )


def init_db():
    """Create Novus tables and safely apply required schema updates."""
    with get_db_connection() as conn:
        with conn.cursor() as cursor:

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    full_name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS resumes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    title TEXT NOT NULL,
                    source_type TEXT DEFAULT 'created',
                    uploaded_filename TEXT,
                    extracted_text TEXT,
                    personal_info TEXT,
                    summary TEXT,
                    education TEXT,
                    skills TEXT,
                    projects TEXT,
                    experience TEXT,
                    certifications TEXT,
                    custom_sections TEXT,
                    completion INTEGER DEFAULT 0,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    resume_number INTEGER
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS ats_analyses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    resume_id BIGINT NOT NULL REFERENCES resumes(id),
                    resume_title TEXT NOT NULL,
                    job_title TEXT,
                    job_description TEXT NOT NULL,
                    score DOUBLE PRECISION,
                    analysis_json TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    analysis_number INTEGER
                )
            """)

            # Check and add any required resume columns.
            cursor.execute("""
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = 'public'
                  AND table_name = 'resumes'
            """)
            resume_columns = {
                row["column_name"] for row in cursor.fetchall()
            }

            resume_migrations = {
                "source_type": "TEXT DEFAULT 'created'",
                "uploaded_filename": "TEXT",
                "extracted_text": "TEXT",
                "resume_number": "INTEGER",
            }

            for column_name, definition in resume_migrations.items():
                if column_name not in resume_columns:
                    cursor.execute(
                        f"ALTER TABLE resumes ADD COLUMN {column_name} {definition}"
                    )

            # Assign display numbers to resumes that do not have one.
            cursor.execute("""
                SELECT DISTINCT user_id
                FROM resumes
                WHERE resume_number IS NULL
            """)
            users_with_unnumbered_resumes = cursor.fetchall()

            for user_row in users_with_unnumbered_resumes:
                user_id = user_row["user_id"]

                cursor.execute("""
                    SELECT id
                    FROM resumes
                    WHERE user_id = %s
                    ORDER BY created_at ASC, id ASC
                """, (user_id,))
                resume_rows = cursor.fetchall()

                for position, resume_row in enumerate(resume_rows, start=1):
                    cursor.execute("""
                        UPDATE resumes
                        SET resume_number = %s
                        WHERE id = %s AND user_id = %s
                          AND resume_number IS NULL
                    """, (position, resume_row["id"], user_id))

            # Check and add the ATS analysis numbering column.
            cursor.execute("""
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = 'public'
                  AND table_name = 'ats_analyses'
            """)
            analysis_columns = {
                row["column_name"] for row in cursor.fetchall()
            }

            if "analysis_number" not in analysis_columns:
                cursor.execute("""
                    ALTER TABLE ats_analyses
                    ADD COLUMN analysis_number INTEGER
                """)

            # Assign display numbers to older analysis records if needed.
            cursor.execute("""
                SELECT DISTINCT user_id
                FROM ats_analyses
                WHERE analysis_number IS NULL
            """)
            users_with_unnumbered_analyses = cursor.fetchall()

            for user_row in users_with_unnumbered_analyses:
                user_id = user_row["user_id"]

                cursor.execute("""
                    SELECT id
                    FROM ats_analyses
                    WHERE user_id = %s
                    ORDER BY created_at ASC, id ASC
                """, (user_id,))
                analysis_rows = cursor.fetchall()

                for position, analysis_row in enumerate(analysis_rows, start=1):
                    cursor.execute("""
                        UPDATE ats_analyses
                        SET analysis_number = %s
                        WHERE id = %s AND user_id = %s
                          AND analysis_number IS NULL
                    """, (position, analysis_row["id"], user_id))

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_ats_analyses_user_created
                ON ats_analyses(user_id, created_at DESC)
            """)

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_ats_analyses_resume_created
                ON ats_analyses(resume_id, created_at DESC)
            """)

    print("Novus PostgreSQL database initialized successfully.")
